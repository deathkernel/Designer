import { SqlProject, SqlTable, SqlColumn } from "@/core/schema/types";

function quoteIdentifier(value: string, dialect: SqlProject["dialect"]): string {
  const escaped = value.replaceAll(dialect === "mysql" ? "`" : '"', dialect === "mysql" ? "``" : '""');
  return dialect === "mysql" ? `\x60${escaped}\x60` : `"${escaped}"`;
}

function columnType(column: SqlColumn, dialect: SqlProject["dialect"]): string {
  if (column.type === "VARCHAR") return `VARCHAR(${column.length || 255})`;
  if (column.type === "DECIMAL") return "DECIMAL(10, 2)";
  if (column.type === "UUID" && dialect === "mysql") return "CHAR(36)";
  if (column.type === "UUID" && dialect === "sqlite") return "TEXT";
  if (column.type === "JSON" && dialect === "sqlite") return "TEXT";
  if (column.type === "BOOLEAN" && dialect === "sqlite") return "INTEGER";
  return column.type;
}

function renderTable(table: SqlTable, project: SqlProject): string {
  const q = (name: string) => quoteIdentifier(name, project.dialect);
  const lines = table.columns.map((column) => {
    const parts = [q(column.name), columnType(column, project.dialect)];
    if (column.autoIncrement) {
      if (project.dialect === "postgresql" && ["INT", "BIGINT", "SMALLINT"].includes(column.type)) {
        parts[1] = column.type === "BIGINT" ? "BIGSERIAL" : "SERIAL";
      } else if (project.dialect === "mysql") {
        parts.push("AUTO_INCREMENT");
      } else if (project.dialect === "sqlite" && column.primaryKey) {
        parts[1] = "INTEGER";
      }
    }
    if (!column.nullable || column.primaryKey) parts.push("NOT NULL");
    if (column.unique && !column.primaryKey) parts.push("UNIQUE");
    if (column.defaultValue?.trim()) parts.push(`DEFAULT ${column.defaultValue.trim()}`);
    return `  ${parts.join(" ")}`;
  });

  const primaryKeys = table.columns.filter((column) => column.primaryKey).map((column) => q(column.name));
  if (primaryKeys.length && project.dialect !== "sqlite") {
    lines.push(`  PRIMARY KEY (${primaryKeys.join(", ")})`);
  } else if (primaryKeys.length && project.dialect === "sqlite") {
    const pkColumn = table.columns.find((column) => column.primaryKey);
    if (primaryKeys.length > 1) lines.push(`  PRIMARY KEY (${primaryKeys.join(", ")})`);
    else if (pkColumn) {
      const index = table.columns.findIndex((column) => column.id === pkColumn.id);
      lines[index] = lines[index].replace("INTEGER NOT NULL", "INTEGER PRIMARY KEY AUTOINCREMENT");
      lines[index] = lines[index].replace("INTEGER", "INTEGER PRIMARY KEY");
    }
  }

  return `CREATE TABLE ${q(table.name)} (\n${lines.join(",\n")}\n);`;
}

export function generateSql(project: SqlProject): string {
  const q = (name: string) => quoteIdentifier(name, project.dialect);
  const statements = project.tables.map((table) => renderTable(table, project));

  for (const relation of project.relations) {
    const source = project.tables.find((table) => table.id === relation.sourceTableId);
    const target = project.tables.find((table) => table.id === relation.targetTableId);
    const sourceColumn = source?.columns.find((column) => column.id === relation.sourceColumnId);
    const targetColumn = target?.columns.find((column) => column.id === relation.targetColumnId);
    if (!source || !target || !sourceColumn || !targetColumn) continue;
    statements.push(
      `ALTER TABLE ${q(source.name)} ADD CONSTRAINT ${q(relation.name)} FOREIGN KEY (${q(sourceColumn.name)}) REFERENCES ${q(target.name)} (${q(targetColumn.name)}) ON DELETE ${relation.onDelete};`
    );
  }

  return `-- Generated by ProjectForge SQL\n-- Dialect: ${project.dialect}\n\n${statements.join("\n\n")}`;
}
